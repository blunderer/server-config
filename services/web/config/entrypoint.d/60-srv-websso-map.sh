#!/bin/sh
# Generate /tmp/websso-allowed.conf (map $host -> comma-separated allowed_emails)
# from the per-domain allowlists in /users/websso/<domain>.
set -eu

lower() {
	printf '%s' "$1" | tr '[:upper:]' '[:lower:]'
}

dir=${WEBSSO_USERS_DIR:-/users/websso}
out=${WEBSSO_MAP_FILE:-/tmp/websso-allowed.conf}
tmp=$(mktemp "${out}.tmp.XXXXXX")
trap 'rm -f "$tmp"' EXIT
srv_host=$(lower "${WEBSSO_HOST:-@host@}")
srv_domain=$(lower "${WEBSSO_DOMAIN:-@domain@}")
srv_hosts=$(lower "${WEBSSO_HOSTS:-@hosts@}")

valid_name() {
	case $1 in
		'' | .* | *~ | *.bak | *.old | *.orig | *.tmp | *.swp | *[!A-Za-z0-9.-]*)
			return 1
			;;
	esac
	return 0
}

present=" "
if [ -d "$dir" ]; then
	for f in "$dir"/*; do
		[ -f "$f" ] || continue
		name=${f##*/}
		valid_name "$name" || continue
		host=$(lower "$name")
		present="${present}${host} "
	done
fi

(
	umask 077
	emitted=" "
	{
		printf '# Generated by 60-srv-websso-map.sh from %s/<domain>.\n' "$dir"
		printf "map \$host \$sso_allowed_emails {\n"
		printf '\thostnames;\n'
		printf '\tdefault "__none__";\n'
		if [ -d "$dir" ]; then
			for f in "$dir"/*; do
				[ -f "$f" ] || continue
				name=${f##*/}
				valid_name "$name" || continue
				host=$(lower "$name")
				emails=$(awk '
					function enc(s) {
						gsub(/%/, "%25", s)
						gsub(/\+/, "%2B", s)
						gsub(/&/, "%26", s)
						gsub(/;/, "%3B", s)
						gsub(/=/, "%3D", s)
						gsub(/\?/, "%3F", s)
						gsub(/"/, "%22", s)
						gsub(/\\/, "%5C", s)
						gsub(/\$/, "%24", s)
						return s
					}
					function add(e,    u) {
						u = enc(e)
						if (!(u in seen)) {
							seen[u] = 1
							list = (list == "" ? u : list "," u)
						}
					}
					{
						sub(/#.*/, "")
						gsub(/^[[:space:]]+|[[:space:]]+$/, "")
						if ($0 == "" || $0 ~ /[[:space:],]/ || $0 !~ /^[^@]+@[^@]+\.[^@]+$/) next
						add($0)
						low = tolower($0)
						if (low != $0) add(low)
					}
					END { printf "%s", list }
				' "$f")
				if [ -n "$emails" ]; then
					case $emitted in
						*" $host "*) ;;
						*)
							printf '\t%s "%s";\n' "$host" "$emails"
							emitted="${emitted}${host} "
							;;
					esac
					# Mirror single-label <sub>.<domain> allowlists onto <sub>.<host>.<domain>
					# unless an explicit per-host allowlist file exists.
					case $srv_host in
						'' | *@* | *.*) ;;
						*)
							case $srv_domain in
								'' | *@*) ;;
								*)
									case $host in
										*."$srv_domain")
											sub=${host%."$srv_domain"}
											case $sub in
												'' | *.*) ;;
												*)
													case " $srv_host $srv_hosts " in
														*" $sub "*) ;;
														*)
															alias="${sub}.${srv_host}.${srv_domain}"
															case "${present}${emitted}" in
																*" $alias "*) ;;
																*)
																	printf '\t%s "%s";\n' "$alias" "$emails"
																	emitted="${emitted}${alias} "
																	;;
															esac
															;;
													esac
													;;
											esac
											;;
									esac
									;;
							esac
							;;
					esac
				fi
			done
		fi
		printf '}\n'
	} >"$tmp"
)
mv -f "$tmp" "$out"
